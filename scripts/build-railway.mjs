import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';

const root = process.cwd();
const distHtmlPath = path.join(root, 'dist', 'index.html');
const outDir = path.join(root, 'deploy');
const outFile = path.join(outDir, 'railway-function.ts');

if (!fs.existsSync(distHtmlPath)) {
  console.error('Missing dist/index.html. Run `npm run build` first.');
  process.exit(1);
}

const rawHtml = fs.readFileSync(distHtmlPath);
const gzipped = zlib.gzipSync(rawHtml, { level: 9 });
const b64 = gzipped.toString('base64');

const serverSource = `// Auto-generated by scripts/build-railway.mjs
const HTML_GZIP_B64 = "${b64}";
const HTML_GZIP_BYTES = Buffer.from(HTML_GZIP_B64, "base64");
const HTML_RAW_BYTES = Bun.gunzipSync(HTML_GZIP_BYTES);

const MANIFEST = JSON.stringify({
  name: "QuietBrief",
  short_name: "QuietBrief",
  description: "Bot-free local meeting transcription & on-device executive action briefs.",
  start_url: "/",
  display: "standalone",
  background_color: "#0b0d12",
  theme_color: "#0b0d12",
  icons: [{ src: "/icon.svg", sizes: "any", type: "image/svg+xml" }]
});

const ICON_SVG = \`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><rect width="64" height="64" rx="16" fill="#10b981"/><path d="M18 24v16M27 16v32M36 20v24M45 28v8" stroke="#07100c" stroke-width="5" stroke-linecap="round"/></svg>\`;

const SW_JS = \`const CACHE = "quietbrief-shell-v1";
self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(["/", "/manifest.webmanifest", "/icon.svg"])));
  self.skipWaiting();
});
self.addEventListener("activate", (e) => {
  e.waitUntil(self.clients.claim());
});
self.addEventListener("fetch", (e) => {
  if (e.request.method !== "GET") return;
  const url = new URL(e.request.url);
  if (url.origin !== self.location.origin || url.pathname.startsWith("/api/")) return;
  e.respondWith(
    caches.match(e.request).then((cached) => cached || fetch(e.request).then((res) => {
      if (res.ok) {
        const clone = res.clone();
        caches.open(CACHE).then((c) => c.put(e.request, clone));
      }
      return res;
    }))
  );
});\`;

const port = Number(Bun.env.PORT || 3000);

Bun.serve({
  port,
  fetch(req) {
    const url = new URL(req.url);

    if (url.pathname === "/api/health") {
      return Response.json({
        ok: true,
        service: "quietbrief",
        architecture: "local-first-on-device",
        timestamp: new Date().toISOString(),
      });
    }

    if (url.pathname === "/manifest.webmanifest") {
      return new Response(MANIFEST, {
        headers: { "Content-Type": "application/manifest+json; charset=utf-8" },
      });
    }

    if (url.pathname === "/icon.svg") {
      return new Response(ICON_SVG, {
        headers: {
          "Content-Type": "image/svg+xml; charset=utf-8",
          "Cache-Control": "public, max-age=86400",
        },
      });
    }

    if (url.pathname === "/sw.js") {
      return new Response(SW_JS, {
        headers: {
          "Content-Type": "application/javascript; charset=utf-8",
          "Cache-Control": "no-cache",
        },
      });
    }

    const acceptsGzip = (req.headers.get("accept-encoding") || "").includes("gzip");
    if (acceptsGzip) {
      return new Response(HTML_GZIP_BYTES, {
        headers: {
          "Content-Type": "text/html; charset=utf-8",
          "Content-Encoding": "gzip",
          "Vary": "Accept-Encoding",
          "X-Content-Type-Options": "nosniff",
        },
      });
    }

    return new Response(HTML_RAW_BYTES, {
      headers: {
        "Content-Type": "text/html; charset=utf-8",
        "X-Content-Type-Options": "nosniff",
      },
    });
  },
});
`;

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(outFile, serverSource, 'utf8');

const byteSize = Buffer.byteLength(serverSource, 'utf8');
const limitBytes = 96 * 1024;
console.log(
  `Built deploy/railway-function.ts (${byteSize} bytes / ${limitBytes} byte Railway Function limit, raw HTML: ${rawHtml.length} bytes, gzipped: ${gzipped.length} bytes).`
);
if (byteSize > limitBytes) {
  console.error(`ERROR: deploy/railway-function.ts exceeds Railway Function 96 KB limit!`);
  process.exit(1);
}
